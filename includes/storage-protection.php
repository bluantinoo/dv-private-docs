<?php
/**
 * Storage protection for the private documents directory
 *
 * The documents live inside the web root, so the only thing standing between
 * them and the open internet is the .htaccess in their folder. Two rules follow
 * from that, and this file exists to enforce both:
 *
 * 1. The protection is written whenever it is missing, not only when the plugin
 *    creates the directory. A directory that arrives already populated (git
 *    deploy, rsync, restored backup) used to skip protection entirely.
 * 2. The plugin verifies from the outside that Apache is actually honouring it.
 *    A correct .htaccess on a server with AllowOverride None protects nothing,
 *    and nothing in the filesystem reveals that.
 *
 * The versioned .htaccess shipped inside wp-content/private-docs/ is the primary
 * defence; everything here is the second line, for environments where that file
 * was lost or never deployed.
 *
 * @package DV_Private_Docs
 */

// Exit if accessed directly
if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

// Bumped whenever the generated .htaccess changes, so old copies get upgraded.
define( 'DV_PRIVATE_DOCS_PROTECTION_VERSION', 2 );

// Name of the file used to probe the directory over HTTP.
define( 'DV_PRIVATE_DOCS_PROBE_FILE', 'dv-protection-probe.txt' );

/**
 * Absolute path of the private documents directory
 *
 * @return string
 */
function dv_private_docs_dir() {
	return WP_CONTENT_DIR . '/' . DV_PRIVATE_DOCS_DIR;
}

/**
 * Contents of the .htaccess that protects the storage directory
 *
 * Apache 2.4 syntax first, with the 2.2 form kept as a fallback for servers
 * without mod_authz_core. Using only "Deny from all" on a 2.4 server without
 * mod_access_compat either does nothing or throws a 500.
 *
 * @return string
 */
function dv_private_docs_htaccess_contents() {
	$lines = array(
		'# DV Private Documents - deny all direct access',
		'# dv-protection-version: ' . DV_PRIVATE_DOCS_PROTECTION_VERSION,
		'# Generated by the DV Private Documents plugin. Edits are overwritten.',
		'',
		'<IfModule mod_authz_core.c>',
		'	Require all denied',
		'</IfModule>',
		'<IfModule !mod_authz_core.c>',
		'	Order deny,allow',
		'	Deny from all',
		'</IfModule>',
		'',
		'# Belt and braces: never execute anything stored here, whatever the',
		'# server decides these files are.',
		'<IfModule mod_php.c>',
		'	php_flag engine off',
		'</IfModule>',
		'<IfModule mod_mime.c>',
		'	RemoveHandler .php .phtml .php3 .php4 .php5 .php7 .php8 .phps',
		'	RemoveType .php .phtml .php3 .php4 .php5 .php7 .php8 .phps',
		'</IfModule>',
		'',
	);

	return implode( "\n", $lines );
}

/**
 * Whether an existing .htaccess should be replaced
 *
 * Replaced when it is one of ours and outdated, or when it contains no deny
 * directive at all. A hand written file that does deny access is left alone:
 * a stricter server-side rule is not ours to overwrite.
 *
 * @param string $contents Current file contents.
 * @return bool
 */
function dv_private_docs_htaccess_needs_rewrite( $contents ) {
	// Ours, and older than the current version.
	if ( preg_match( '/dv-protection-version:\s*(\d+)/', $contents, $matches ) ) {
		return (int) $matches[1] < DV_PRIVATE_DOCS_PROTECTION_VERSION;
	}

	// Ours too, from before the version marker existed. It carries the Apache
	// 2.2 syntax only, which on a 2.4 server without mod_access_compat protects
	// nothing, so it must be upgraded even though it looks like a deny rule.
	if ( false !== strpos( $contents, 'DV Private Docs - Deny all direct access' ) ) {
		return true;
	}

	// Not ours, but denying access one way or another: leave it be.
	if ( preg_match( '/Require\s+all\s+denied|Deny\s+from\s+all/i', $contents ) ) {
		return false;
	}

	// Present but protecting nothing.
	return true;
}

/**
 * Create the storage directory if needed and make sure it is protected
 *
 * Safe to call on every write path: it only touches the filesystem when
 * something is actually missing or outdated.
 *
 * @return bool True when the directory exists and carries a protecting .htaccess.
 */
function dv_ensure_private_dir_protection() {
	$private_dir = dv_private_docs_dir();

	if ( ! file_exists( $private_dir ) && ! wp_mkdir_p( $private_dir ) ) {
		update_option( 'dv_private_docs_protection_fs', 'failed', false );
		return false;
	}

	$htaccess = $private_dir . '/.htaccess';
	$write    = true;

	if ( file_exists( $htaccess ) ) {
		$current = file_get_contents( $htaccess );
		$write   = ( false === $current ) || dv_private_docs_htaccess_needs_rewrite( $current );
	}

	if ( $write ) {
		file_put_contents( $htaccess, dv_private_docs_htaccess_contents() );
	}

	// Directory listing fallback for servers that ignore .htaccess entirely.
	$index = $private_dir . '/index.php';
	if ( ! file_exists( $index ) ) {
		file_put_contents( $index, "<?php\n// Silence is golden.\n" );
	}

	$protected = file_exists( $htaccess );
	update_option( 'dv_private_docs_protection_fs', $protected ? 'ok' : 'failed', false );

	return $protected;
}

/**
 * Periodic protection check in the admin
 *
 * Cheap filesystem pass on every admin load is still too much, so it runs at
 * most once an hour. The HTTP probe, which costs a real request, runs weekly.
 */
function dv_private_docs_maybe_check_protection() {
	if ( ! current_user_can( 'manage_options' ) ) {
		return;
	}

	if ( get_transient( 'dv_private_docs_protection_checked' ) ) {
		return;
	}
	set_transient( 'dv_private_docs_protection_checked', 1, HOUR_IN_SECONDS );

	dv_ensure_private_dir_protection();

	if ( ! get_transient( 'dv_private_docs_probe_checked' ) ) {
		set_transient( 'dv_private_docs_probe_checked', 1, WEEK_IN_SECONDS );
		dv_private_docs_probe_public_access();
	}
}
add_action( 'admin_init', 'dv_private_docs_maybe_check_protection' );

/**
 * Ask the web server, from the outside, whether the directory is readable
 *
 * Writes a file with a random token, requests it over HTTP and looks for the
 * token in the response body. Getting the token back means Apache is serving
 * the directory and every document in it is public.
 *
 * @return void
 */
function dv_private_docs_probe_public_access() {
	$private_dir = dv_private_docs_dir();
	if ( ! is_dir( $private_dir ) ) {
		return;
	}

	$token = 'dvprobe-' . wp_generate_password( 24, false );
	$path  = $private_dir . '/' . DV_PRIVATE_DOCS_PROBE_FILE;

	if ( false === file_put_contents( $path, $token ) ) {
		return;
	}

	$url      = content_url( DV_PRIVATE_DOCS_DIR . '/' . DV_PRIVATE_DOCS_PROBE_FILE );
	$response = wp_remote_get(
		$url,
		array(
			'timeout'   => 10,
			'sslverify' => 'local' !== wp_get_environment_type(),
			// The probe must reach the web server, not a cached copy.
			'headers'   => array( 'Cache-Control' => 'no-cache' ),
		)
	);

	@unlink( $path );

	// A failed request tells us nothing about exposure, so it is not a verdict.
	if ( is_wp_error( $response ) ) {
		update_option( 'dv_private_docs_protection_http', 'unknown', false );
		return;
	}

	$exposed = ( false !== strpos( wp_remote_retrieve_body( $response ), $token ) );
	update_option( 'dv_private_docs_protection_http', $exposed ? 'exposed' : 'ok', false );
}

/**
 * Admin notice when the storage directory is not protected
 */
function dv_private_docs_protection_notice() {
	if ( ! current_user_can( 'manage_options' ) ) {
		return;
	}

	$http = get_option( 'dv_private_docs_protection_http' );
	$fs   = get_option( 'dv_private_docs_protection_fs' );

	if ( 'exposed' === $http ) {
		printf(
			'<div class="notice notice-error"><p><strong>%s</strong> %s</p></div>',
			esc_html__( 'DV Private Documents: the private documents are publicly downloadable.', 'dv-private-docs' ),
			esc_html__( 'A test file in the storage directory was served over HTTP without authentication. The web server is ignoring the .htaccess protection, so the directory must be blocked at server level before any document is uploaded.', 'dv-private-docs' )
		);
		return;
	}

	if ( 'failed' === $fs ) {
		printf(
			'<div class="notice notice-error"><p><strong>%s</strong> %s</p></div>',
			esc_html__( 'DV Private Documents: the storage directory could not be protected.', 'dv-private-docs' ),
			esc_html__( 'The plugin was unable to create or write the .htaccess file that keeps the private documents from being downloaded directly. Check the filesystem permissions on wp-content/private-docs/.', 'dv-private-docs' )
		);
	}
}
add_action( 'admin_notices', 'dv_private_docs_protection_notice' );
